export function extOf(path) {
  const n = path.split("/").pop().toLowerCase();
  if (
    n === "dockerfile" ||
    n === "makefile" ||
    n === ".gitignore" ||
    n === ".clang-format"
  )
    return n.replace(".", "");
  const i = n.lastIndexOf(".");
  return i < 0 ? "" : n.slice(i + 1);
}
export function langOf(path) {
  const e = extOf(path);
  return EXT_LANG[e] || ["plain", e ? e.toUpperCase() : "Texte"];
}
